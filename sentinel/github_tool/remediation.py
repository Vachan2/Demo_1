"""
github_tool/remediation.py

Orchestrates patch generation and PR creation for a given RCA result.

Steps:
  1. Read the affected file from the repo
  2. Apply the fix (LLM-generated or rule-based)
  3. Create a feature branch
  4. Write the patched file
  5. Write a regression test
  6. Commit
  7. Open a PR

Selects local_git or github_api backend based on configuration.
"""
